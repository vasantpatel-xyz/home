// Bundles everything under public/ into src/assets.generated.js so the worker
// serves the pages itself (no separate asset upload step). Run by deploy.sh,
// test-local.sh and `npm run dev`. Text files are embedded as strings, anything
// else as base64.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8',
  '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon', '.woff2': 'font/woff2', '.woff': 'font/woff', '.pdf': 'application/pdf',
};
const TEXT = new Set(['.html', '.css', '.js', '.json', '.svg', '.txt', '.webmanifest']);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}
const files = walk(pub).sort();
const entries = files.map((f) => {
  const ext = extname(f).toLowerCase();
  const key = '/' + relative(pub, f).split('\\').join('/');
  const type = TYPES[ext] || 'application/octet-stream';
  if (TEXT.has(ext)) return `  ${JSON.stringify(key)}: { t: ${JSON.stringify(type)}, b: ${JSON.stringify(readFileSync(f, 'utf8'))} }`;
  return `  ${JSON.stringify(key)}: { t: ${JSON.stringify(type)}, bin: true, b: ${JSON.stringify(readFileSync(f).toString('base64'))} }`;
});
const out = `// GENERATED by scripts/bundle-assets.mjs from public/ — do not edit.\nexport default {\n${entries.join(',\n')}\n};\n`;
mkdirSync(join(root, 'src'), { recursive: true });
writeFileSync(join(root, 'src', 'assets.generated.js'), out);
const bytes = Buffer.byteLength(out);
console.log(`bundled ${files.length} files from public/ into src/assets.generated.js (${(bytes / 1024).toFixed(1)} KiB)`);
